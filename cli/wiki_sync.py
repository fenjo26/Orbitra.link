#!/usr/bin/env python3
"""Build the GitHub wiki from docs/.

docs/ is the source of truth; the wiki is a generated mirror. The script writes
the pages into a local clone of the wiki repository, you review and push:

    git clone https://github.com/fenjo26/Orbitra.link.wiki.git ../Orbitra.link.wiki
    python3 cli/wiki_sync.py ../Orbitra.link.wiki
    cd ../Orbitra.link.wiki && git add -A && git commit -m "Sync from docs" && git push

(GitHub creates the wiki repository only after the first page is saved through
the web UI — create any page once, then clone.)

What it does:
  * every docs/*.md becomes a page (names in PAGE_NAMES below, index.md -> Home);
    its "# " heading is dropped because the wiki prints the page name itself;
  * docs/_Sidebar.md becomes the sidebar, a footer points editors back to docs/;
  * links between docs pages are rewritten to wiki page names (anchors kept);
    links to repository files (../CHANGELOG.md, archive/…) become GitHub URLs;
  * pages it generated earlier but no longer produces are removed — it
    recognises them by the marker comment, hand-written wiki pages are left alone.

Standard library only; run it from anywhere.
"""

import os
import re
import sys

REPO_URL = "https://github.com/fenjo26/Orbitra.link"
BRANCH = "main"
MARKER = "<!-- generated by cli/wiki_sync.py from docs/{src} — edit docs/, not the wiki -->"
MARKER_RE = re.compile(r"<!-- generated by cli/wiki_sync\.py from docs/")
LINK_RE = re.compile(r"(\]\()([^)\s]+)(\))")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")


