# Screenshots and other images are embedded from the repository's raw host:
# a github.com/…/blob/… link is an HTML page and would not render inline.
IMAGE_EXT = (".webp", ".png", ".jpg", ".jpeg", ".gif", ".svg")


def page_name(src):
    name = PAGE_NAMES.get(src, src[:-3])
    # Page names are file names and link targets: no spaces or brackets.
    return re.sub(r"[^\w.-]+", "-", name, flags=re.UNICODE).strip("-")


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: python3 cli/wiki_sync.py <path to the wiki clone>")
    wiki = os.path.abspath(sys.argv[1])
    if not os.path.isdir(os.path.join(wiki, ".git")):
        sys.exit(f"{wiki} is not a git clone of the wiki (no .git)")

    sources = sorted(f for f in os.listdir(DOCS)
                     if f.endswith(".md") and not f.startswith("_"))
    texts = {f: open(os.path.join(DOCS, f), encoding="utf-8").read() for f in sources}

    # Drift guard: the "current for vX" line in the index pages is the first
    # thing a reader sees, and it lags releases silently (it said v1.8.0 while
    # the tracker shipped 1.8.8). Warn — do not block — when it disagrees with
    # version.json, the release source of truth.
    try:
        import json
        released = json.load(open(os.path.join(ROOT, "version.json"), encoding="utf-8"))["version"]
        # docs/ru/ pages are GitHub-only (the wiki mirrors EN docs alone), so
        # the RU index is read from disk, not from `texts`.
        for idx, text in [("index.md", texts.get("index.md", "")),
                          ("ru/index.md", open(os.path.join(DOCS, "ru", "index.md"),
                                               encoding="utf-8").read())]:
            m = re.search(r"current for \*\*v([\w.]+)\*\*|актуальна для \*\*v([\w.]+)\*\*", text)
            claimed = (m.group(1) or m.group(2)) if m else None
            if claimed and claimed != released:
                print(f"warning: docs/{idx} says the docs are current for v{claimed}, "
                      f"but version.json is at v{released} — bump the line", file=sys.stderr)
    except (OSError, KeyError, ValueError):
        pass
    names = {f: page_name(f) for f in sources}
    dupes = {n for n in names.values() if list(names.values()).count(n) > 1}
    if dupes:
        sys.exit(f"two docs pages share a title: {', '.join(sorted(dupes))}")

    def rewrite(text):
        def fix(m):
            target = m.group(2)
            if re.match(r"^[a-z]+:", target) or target.startswith("#"):
                return m.group(0)
            path, _, anchor = target.partition("#")
            anchor = "#" + anchor if anchor else ""
            if path in names:
                return m.group(1) + names[path] + anchor + m.group(3)
            # Anything else lives in the repository: link to it on GitHub.
            repo_path = os.path.normpath(os.path.join("docs", path)).replace(os.sep, "/")
            if repo_path.startswith(".."):
                return m.group(0)
            if path.lower().endswith(IMAGE_EXT):
                raw = REPO_URL.replace("https://github.com/", "https://raw.githubusercontent.com/")
                return f"{m.group(1)}{raw}/{BRANCH}/{repo_path}{m.group(3)}"
            kind = "tree" if path.endswith("/") or os.path.isdir(os.path.join(ROOT, repo_path)) else "blob"
            return f"{m.group(1)}{REPO_URL}/{kind}/{BRANCH}/{repo_path}{anchor}{m.group(3)}"
        return LINK_RE.sub(fix, text)

    written = set()
    for src in sources:
        body = texts[src]
        body = re.sub(r"\A\s*# .+\n+", "", body, count=1)  # wiki shows the name
        out = MARKER.format(src=src) + "\n\n" + rewrite(body)
        fname = names[src] + ".md"
        with open(os.path.join(wiki, fname), "w", encoding="utf-8") as fh:
            fh.write(out)
        written.add(fname)

    sidebar = os.path.join(DOCS, "_Sidebar.md")
    if os.path.exists(sidebar):
        text = open(sidebar, encoding="utf-8").read()
        with open(os.path.join(wiki, "_Sidebar.md"), "w", encoding="utf-8") as fh:
            fh.write(MARKER.format(src="_Sidebar.md") + "\n\n" + rewrite(text))
        written.add("_Sidebar.md")

    with open(os.path.join(wiki, "_Footer.md"), "w", encoding="utf-8") as fh:
        fh.write(MARKER.format(src="") + "\n\n"
                 f"Вики собирается из папки [docs/]({REPO_URL}/tree/{BRANCH}/docs) репозитория. "
                 "Правки — через pull request в `docs/`.\n")
    written.add("_Footer.md")

    removed = []
    for f in os.listdir(wiki):
        if f.endswith(".md") and f not in written:
            path = os.path.join(wiki, f)
            with open(path, encoding="utf-8") as fh:
                head = fh.read(300)
            if MARKER_RE.search(head):
                os.remove(path)
                removed.append(f)

    print(f"wrote {len(written)} pages to {wiki}")
    for f in removed:
        print(f"removed stale page {f}")
    print("review with `git -C <wiki> status`, then commit and push")


if __name__ == "__main__":
    main()
