<?php
// cli/api_catalog.php
// Prints the catalogue of api.php actions as Markdown, grouped the way the
// server enforces access: by resource (core/resource_access.php) with the
// read / write split, then the actions every signed-in user may call, then the
// admin-only rest. docs/api.md embeds this output between the
// "api-catalog:begin/end" markers; regenerate it after adding an action:
//
//   php cli/api_catalog.php > /tmp/catalog.md
//   php cli/api_catalog.php --check docs/api.md   # exit 1 when docs/api.md is stale
//
// Read-only: it parses api.php as text and loads only the access map, so it
// needs no database and never touches the tracker's state.

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__);
require_once $root . '/core/resource_access.php';

$src = file_get_contents($root . '/api.php');
$switchPos = strpos($src, "    switch (\$action) {");
if ($src === false || $switchPos === false) {
    fwrite(STDERR, "api.php: top-level switch (\$action) not found\n");
    exit(2);
}
// Top-level cases sit at exactly eight spaces of indentation; nested switches
// inside handlers are indented deeper and are not actions.
preg_match_all("/^        case '([a-z0-9_]+)'/m", substr($src, $switchPos), $m);
$handled = array_fill_keys($m[1], true);

// The cost/revenue aggregator family lives in the switch's default branch
// (`strpos($action, 'aggregator_') === 0`) with its own nested switch.
$aggregator = [];
$aggPos = strpos($src, "strpos(\$action, 'aggregator_') === 0", $switchPos);
if ($aggPos !== false) {
    preg_match_all("/^                    case '(aggregator_[a-z0-9_]+)'/m", substr($src, $aggPos), $am);
    $aggregator = array_values(array_unique($am[1]));
    foreach ($aggregator as $a) {
        $handled[$a] = true;
    }
}

// Archive actions are gated per item type, not by one resource.
$archive = ['archive_items', 'archive_restore', 'archive_purge'];

// Answered before authentication (api.php checks these ahead of the gate).
$public = ['login', 'logout', 'check_setup', 'setup_first_user', 'ping'];

$resourceTitles = [
    'campaigns' => 'Кампании, отчёты по кампаниям, конверсии',
    'offers'    => 'Офферы',
    'landings'  => 'Лендинги и PWA',
    'sources'   => 'Источники трафика',
    'networks'  => 'Партнёрские сети',
    'domains'   => 'Домены, SSL, регистраторы, бэкордер',
    'media'     => 'Галерея контента',
    'push'      => 'Web Push',
    'logs'      => 'Логи',
];

$seen = [];
$fmt = static function (array $actions) use ($handled): string {
    $actions = array_values(array_unique($actions));
    sort($actions);
    $out = [];
    foreach ($actions as $a) {
        // A mapped name with no handler would 400 — mark it rather than hide it.
        $out[] = '`' . $a . '`' . (isset($handled[$a]) ? '' : ' ⚠️');
    }
    return implode(', ', $out);
};

$lines = [];
$lines[] = '<!-- api-catalog:begin — generated by `php cli/api_catalog.php`, do not edit by hand -->';
$lines[] = '';
$lines[] = 'Всего действий в `api.php`: **' . count($handled) . '**.';
$lines[] = '';
$lines[] = '### Без авторизации';
$lines[] = '';
$lines[] = $fmt($public);
foreach ($public as $a) {
    $seen[$a] = true;
}

foreach (orbitraResourceAccessMap() as $resource => $groups) {
    $lines[] = '';
    $lines[] = '### ' . ($resourceTitles[$resource] ?? $resource) . ' — ресурс `' . $resource . '`';
    $lines[] = '';
    foreach (['read' => 'Чтение', 'write' => 'Запись', 'hybrid' => 'GET — чтение, POST — запись'] as $kind => $label) {
        $list = $groups[$kind] ?? [];
        if (!$list) {
            continue;
        }
        $lines[] = '- **' . $label . ':** ' . $fmt($list);
        foreach ($list as $a) {
            $seen[$a] = true;
        }
    }
}

$lines[] = '';
$lines[] = '### Доступно любому вошедшему пользователю';
$lines[] = '';
$lines[] = 'Не привязаны к ресурсу; для не-админов разрешены явно (`orbitraUnmappedAllowedActions()`). '
    . 'Действия с пометкой «только GET» на POST для не-админа отвечают 403.';
$lines[] = '';
$allowed = orbitraUnmappedAllowedActions();
$any = [];
$getOnly = [];
foreach ($allowed as $a => $postToo) {
    $seen[$a] = true;
    if ($postToo) {
        $any[] = $a;
    } else {
        $getOnly[] = $a;
    }
}
$lines[] = '- **GET и POST:** ' . $fmt($any);
$lines[] = '- **Только GET:** ' . $fmt($getOnly);

$lines[] = '';
$lines[] = '### Архив';
$lines[] = '';
$lines[] = $fmt($archive) . ' — список требует доступа на чтение ко всем пяти ресурсам архива, '
    . 'восстановление и удаление — полного доступа к ресурсу удаляемого элемента.';
foreach ($archive as $a) {
    $seen[$a] = true;
}

if ($aggregator) {
    $lines[] = '';
    $lines[] = '### Агрегатор расходов и доходов (только администратор)';
    $lines[] = '';
    $lines[] = $fmt($aggregator);
    foreach ($aggregator as $a) {
        $seen[$a] = true;
    }
}

$adminOnly = array_keys(array_diff_key($handled, $seen));
$lines[] = '';
$lines[] = '### Только администратор';
$lines[] = '';
$lines[] = 'Всё, что не перечислено выше, для не-админов закрыто по умолчанию.';
$lines[] = '';
$lines[] = $fmt($adminOnly);
$lines[] = '';
$lines[] = '⚠️ — имя есть в карте доступа, но обработчика в `api.php` нет (запрос ответит ошибкой).';
$lines[] = '';
$lines[] = '<!-- api-catalog:end -->';
$catalog = implode("\n", $lines) . "\n";

if (($argv[1] ?? '') === '--check') {
    $doc = @file_get_contents($argv[2] ?? ($root . '/docs/api.md'));
    if ($doc === false) {
        fwrite(STDERR, "cannot read the document to check\n");
        exit(2);
    }
    if (strpos($doc, $catalog) === false) {
        fwrite(STDERR, "docs/api.md: the action catalogue is stale — regenerate it with php cli/api_catalog.php\n");
        exit(1);
    }
    echo "docs/api.md: action catalogue is current\n";
    exit(0);
}

echo $catalog;
